// ============================================================
// EVALUATION FUNCTION
// ============================================================

int evaluate(const Position& pos) {
    int score = 0;
    uint64_t bb;
    
    // White pieces
    for(int piece = 0; piece < 5; piece++) {  // Skip king for now
        bb = pos.bitboards[WHITE][piece];
        while(bb) {
            int square = __builtin_ctzll(bb);
            score += PIECE_VALUES[piece] + PST[piece][square];
            bb &= bb - 1;
        }
    }
    
    // Black pieces (mirror PST vertically)
    for(int piece = 0; piece < 5; piece++) {
        bb = pos.bitboards[BLACK][piece];
        while(bb) {
            int square = __builtin_ctzll(bb);
            score -= PIECE_VALUES[piece] + PST[piece][square ^ 56];
            bb &= bb - 1;
        }
    }
    
    // Add king safety (simplified)
    int white_king = __builtin_ctzll(pos.bitboards[WHITE][KING]);
    int black_king = __builtin_ctzll(pos.bitboards[BLACK][KING]);
    
    score += PST[KING][white_king];
    score -= PST[KING][black_king ^ 56];
    
    return score;
}
